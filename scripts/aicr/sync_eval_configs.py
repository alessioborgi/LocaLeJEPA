CAMPAIGN = REPO / "configs" / "campaign"

BANNER = ("# GENERATED by scripts/aicr/sync_eval_configs.py from configs/campaign/*.yaml -- do not edit\n"
          "# by hand: edit the manifest and re-run the script. Run names are the checkpoint directories\n"
          "# (F35 closed by construction); tests/unit/test_eval_config_names_manifest_runs.py fails\n"
          "# when this file is stale.\n")

IN1K_128 = ["in1k_baselines.yaml", "in1k_local.yaml", "in1k_global_ball.yaml", "capacity_in1k.yaml",
            "in1k_attribution.yaml"]
# capacity_in1k is the depth x K grid (decision 25). Its tag is `vit_capdep` rather than something
# like `cap1k_vit` because `family()` below matches `tag == prefix or tag.startswith(prefix + "_")`
# and RAISES otherwise -- at module import, which would break collection of
# tests/unit/test_eval_config_names_manifest_runs.py rather than failing one assertion.
# in1k_global_ball is the K=1 ball control (decision 22, run 3). It MUST be listed here: a run whose
# checkpoint exists but which no eval config names is a silently dropped row -- the F35 failure this
# whole generator exists to prevent. The Imagenette manifests (target_and_centering,
# ablation_grid_ep800_d4) are deliberately absent: they are evaluated through
# make_ablation_eval_config.py from their own grid JSON, not from here.
VITL = ["in1k_vitl14.yaml", "in1k_vitl14_globalball.yaml"]
# The ViT-L global ball is in VITL rather than IN1K_128 because this list renders at crop 238 and
# that one at 128 -- and because `submit_command` builds one homogeneous array per grid, so an
# 8-GPU run cannot share a manifest with the 4-GPU controls (decision 26).
TORUS = ["torus.yaml"]


def family(run: C.RunSpec) -> str:
    for prefix in ("vitl14", "d4rn50", "hvit", "vit", "svit", "nvit"):
        if run.tag == prefix or run.tag.startswith(prefix + "_"):
            return prefix
    raise ValueError(f"no backbone family for tag {run.tag!r}")


def runs(manifests: list[str]) -> list[C.RunSpec]:
    out: list[C.RunSpec] = []
    for name in manifests:
        out += C.expand(C.load_manifest(CAMPAIGN / name))
    return out


def _shape(run: C.RunSpec) -> str:
    """The `overrides:` line an entry needs to rebuild its own architecture, or nothing.

    Without this, a run whose architecture comes from a MANIFEST override is rebuilt at its
    experiment's default: `capacity_in1k` trains at `model.encoder.depth` 6 and 3, while
    `lejepa/vit_in1k_localballreg_depth` composes to 12, so every one of its checkpoints would meet
    a 12-layer module. `src/eval/extract.py:134-140` raises on the strict key check, so it fails
    loudly -- but only after the eval has been queued, extracted and started.
    See `C.MODEL_SHAPE_KEYS` for what counts and why `data.crop_size` does not.
    """
    keys = C.shape_overrides(run.overrides)
    return f"    overrides: [{', '.join(repr(k) for k in keys)}]\n" if keys else ""


def backbone_entries(specs: list[C.RunSpec], *, best_twins: bool, with_family: bool = False) -> str:
    lines = []
    for run in specs:
        fam = f"    family: {family(run)}\n" if with_family else ""
        lines.append(f"  - name: {run.run_name}\n    experiment: {run.experiment}\n{fam}{_shape(run)}"
                     f"    checkpoint: checkpoints/{run.run_name}/last.ckpt\n")
    if best_twins:
        lines.append("  # ---- the online probe's checkpoint (best val/probe_acc): the labelled secondary column ----\n")
        for run in specs:
            fam = f"    family: {family(run)}\n" if with_family else ""
            lines.append(f"  - name: {run.run_name}_best\n    experiment: {run.experiment}\n{fam}{_shape(run)}"
                         f"    checkpoint: checkpoints/{run.run_name}/best.ckpt\n")
    return "".join(lines)


