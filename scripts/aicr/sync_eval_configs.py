"""Render every campaign evaluation config from the campaign manifests.

F35: three checkpoint-naming conventions coexisted and a mismatch between an eval config's
``checkpoint:`` and a run's directory was a *silently dropped row*. The manifests in
``configs/campaign/`` are now the single source of run names, and the checkpoint directory IS
the run name -- so the eval configs are derived, not written. When Phase 4 declares (lambda, K)
and the manifests change, re-running this script changes every consumer at once, and
``tests/unit/test_eval_config_names_manifest_runs.py`` fails until it has been re-run.

    python scripts/aicr/sync_eval_configs.py           # rewrite the generated configs
    python scripts/aicr/sync_eval_configs.py --check   # exit 1 if any of them is stale

Headline rows read ``last.ckpt`` (state/10-PAPER-STATE.md PD-4: no selection on the reported
split); the in-domain configs also carry ``<run>_best`` twins reading ``best.ckpt`` for the
labelled secondary column.
"""

