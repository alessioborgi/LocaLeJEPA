def _load(path):
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    return None


def _ckpt_epoch(path):
    if not os.path.isfile(path):
        return None
    try:
        return torch.load(path, map_location="cpu", weights_only=False, mmap=True).get("epoch")
    except Exception:  # noqa: BLE001
        return None


def _avg(entry):
    vals = [entry["datasets"][k]["top1"] for k, _ in DATASETS if k in entry["datasets"]]
    return sum(vals) / len(vals) if len(vals) == len(DATASETS) else None


def _progress(ckdir):
    last_ep = _ckpt_epoch(f"{ckdir}/last.ckpt")
    if last_ep is not None and last_ep >= MAX_EPOCHS - 1:
        return f"*finished (ep {last_ep}), eval pending*", None
    return f"*pretraining, epoch {last_ep + 1 if last_ep is not None else '?'}/{MAX_EPOCHS}*", last_ep


def _observations(entries):
    """Data-driven bullet points; kept factual so the file regenerates cleanly."""
    out = []
    complete = {n: e for n, e in entries.items() if e is not None and _avg(e) is not None}
    if not complete:
        return "* No backbone has finished all seven datasets yet."
    label = {name: lab for name, lab, _, _ in ROWS}
    bb_of = {name: key for name, _, _, key in ROWS}
    for bb in ("d4rn50", "hvit", "vit"):
        rows = {n: e for n, e in complete.items() if bb_of[n] == bb}
        if not rows:
            continue
        best = max(rows, key=lambda n: _avg(rows[n]))
        base = f"{bb}_sigreg"
        line = f"* **{TEX_BACKBONE[bb].split(' (')[0]}**: best Avg is {label[best]} at {_avg(rows[best]):.1f}"
        if base in rows and best != base:
            line += f" vs {_avg(rows[base]):.1f} for LeJEPA/SIGReg (+{_avg(rows[best]) - _avg(rows[base]):.1f})"
        line += "."
        if base in rows:
            b = rows[base]["datasets"]
            others = {n: e for n, e in rows.items() if n != base}
            if others:
                wins = []
                for k, disp in DATASETS:
                    gains = [e["datasets"][k]["top1"] - b[k]["top1"] for e in others.values()]
                    if all(g > 0 for g in gains):
                        wins.append(disp)
                if wins:
                    line += f" Every regulariser variant beats SIGReg on {', '.join(wins)}."
        out.append(line)
    # per-dataset ranking across everything
    hard = sorted(DATASETS, key=lambda kd: sum(e["datasets"][kd[0]]["top1"] for e in complete.values()) / len(complete))
    out.append(f"* Hardest datasets for every backbone: {hard[0][1]} and {hard[1][1]}; easiest: {hard[-1][1]} "
               f"(the same ordering as the paper's ViT-B/14, where Aircraft is ~10% and CIFAR10 ~82%).")
    out.append("* **Absolute numbers are not comparable to the paper's** (ViT-B/14 at 224 px, 86M params, "
               "batch 512): our backbones are ~4x smaller and both pretrained and probed at 128 px, which "
               "hurts fine-grained datasets (Aircraft, Pets, Flowers) most. Compare rows *within* a backbone.")
    return "\n".join(out)


def main():
    lines = []
    n_done = 0
    entries = {}
    for bb in ("d4rn50", "hvit", "vit"):
        lines += [f"### {BACKBONE_TITLES[bb]}", "",
                  "| Method | Ckpt (epoch) | " + " | ".join(d for _, d in DATASETS) + " | **Avg** |",
                  "|---|---|" + "---|" * (len(DATASETS) + 1)]
        # best value per column for bolding
        col_best = {}
        for k, _ in DATASETS + [("avg", "Avg")]:
            vals = []
            for name, _, _, key in ROWS:
                if key != bb:
                    continue
                e = _load(f"{RESULT_DIR}/{name}.json")
                if e is None:
                    continue
                v = _avg(e) if k == "avg" else e["datasets"].get(k, {}).get("top1")
                if v is not None:
                    vals.append(v)
            col_best[k] = max(vals) if vals else None
        for name, label, ckdir, key in ROWS:
            if key != bb:
                continue
            e = _load(f"{RESULT_DIR}/{name}.json")
            entries[name] = e
            if e is None:
                prog, _ = _progress(ckdir)
                lines.append(f"| {label} | {prog} | " + " | ".join("—" for _ in DATASETS) + " | — |")
                continue
            cells = []
            for k, _ in DATASETS:
                v = e["datasets"].get(k, {}).get("top1")
                if v is None:
                    cells.append("*(pending)*")
                else:
                    s = f"{v:.1f}"
                    cells.append(f"**{s}**" if v == col_best[k] else s)
            avg = _avg(e)
            if avg is None:
                avg_cell = "*(partial)*"
            else:
                n_done += 1
                s = f"{avg:.1f}"
                avg_cell = f"**{s}**" if avg == col_best["avg"] else s
            lines.append(f'| {label} | final (ep {e["epoch"]}) | ' + " | ".join(cells) + f" | {avg_cell} |")
        lines.append("")
    body = "\n".join(lines)
    paper_rows = "\n".join(f"| {m} | " + " | ".join(f"{v:.1f}" for v in vals) + " |" for m, vals in PAPER_ROWS)
    doc = HEADER.format(n_done=n_done, n_rows=len(ROWS), paper_rows=paper_rows) + body \
        + FOOTER.format(observations=_observations(entries))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(doc)
    print(body)
    print(f"\n{n_done}/{len(ROWS)} rows complete -> {OUT}", file=sys.stderr)
    make_tex(entries)


def _tex(label):
    return label.replace("λ", r"$\lambda{=}$").replace("→", r"$\to$").replace("k2", "$k{=}2$") \
        .replace("k4", "$k{=}4$").replace("k1$\\to$10", "$k{=}1\\to10$").replace("$k{=}1$$\\to$10", "$k{=}1\\to10$")


def make_tex(entries):
    rows_out = []
    for bb in ("d4rn50", "hvit", "vit"):
        best = {}
        for k, _ in DATASETS + [("avg", "Avg")]:
            vals = [(_avg(e) if k == "avg" else e["datasets"].get(k, {}).get("top1"))
                    for n, e in entries.items() if e is not None and dict((r[0], r[3]) for r in ROWS)[n] == bb]
            vals = [v for v in vals if v is not None]
            best[k] = max(vals) if vals else None
        rows_out.append(r"\midrule")
        rows_out.append(r"\multicolumn{9}{l}{\textit{" + TEX_BACKBONE[bb] + "}} \\\\")
        for name, label, ckdir, key in ROWS:
            if key != bb:
                continue
            e = entries.get(name)
            lab = _tex(label)
            if e is None:
                prog, last_ep = _progress(ckdir)
                if last_ep is None and "finished" in prog:
                    cell = r"\multicolumn{8}{c}{\textit{Evaluation pending}}"
                else:
                    ep = last_ep + 1 if last_ep is not None else "?"
                    cell = r"\multicolumn{8}{c}{\textit{Training (epoch " + f"{ep}/{MAX_EPOCHS}" + ")}}"
                rows_out.append(f"{lab} & {cell} \\\\")
                continue
            cells = []
            for k, _ in DATASETS:
                v = e["datasets"].get(k, {}).get("top1")
                if v is None:
                    cells.append("--")
                else:
                    s = f"{v:.1f}"
                    cells.append(r"\textbf{" + s + "}" if v == best[k] else s)
            avg = _avg(e)
            if avg is None:
                cells.append("--")
            else:
                s = f"{avg:.1f}"
                cells.append(r"\textbf{" + s + "}" if avg == best["avg"] else s)
            rows_out.append(f"{lab} & " + " & ".join(cells) + " \\\\")

    tex = "\n".join([
        r"%% Auto-generated by scripts/make_transfer_results.py -- do not edit by hand.",
        r"%% Requires: \usepackage{booktabs,amsmath,graphicx}",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Frozen-backbone linear probing accuracy (\%) on downstream datasets of",
        r"D4-equivariant ResNet-50, Hyperbolic ViT-S/8 and plain ViT-S/8 backbones pretrained for 100 epochs on",
        r"ImageNet-1K (crop 128, no EMA), following the protocol of SPHERE-JEPA Table~1: one",
        r"linear layer on standardized frozen features (SGD, 100 epochs, learning rate selected",
        r"on a 10\% held-out slice of the train split), top-1 on the official test split of each",
        r"dataset; Avg is the mean over the seven datasets. All rows use the final epoch-99",
        r"checkpoint; \emph{Training} rows have not reached 100 epochs yet. For reference the",
        r"paper reports an average of 52.4 (LeJEPA) and 54.1 (SPHERE-JEPA) with a ViT-B/14 at",
        r"224\,px; no SUSReg ImageNet-1K checkpoint exists for our backbones.}",
        r"\label{tab:in1k-transfer}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{l ccccccc c}",
        r"\toprule",
        r"Method & DTD & Aircraft & CIFAR10 & CIFAR100 & Flowers & Food & Pets & Avg \\",
        r"\midrule",
        r"\multicolumn{9}{l}{\textit{Reference: SPHERE-JEPA paper, ViT-B/14 (86M), 224\,px, reported}} \\",
        *[f"{m} & " + " & ".join(f"{v:.1f}" for v in vals) + " \\\\" for m, vals in PAPER_ROWS],
        *rows_out,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
    ]) + "\n"
    os.makedirs(os.path.dirname(TEX_OUT), exist_ok=True)
    with open(TEX_OUT, "w", encoding="utf-8") as f:
        f.write(tex)
    print(f"LaTeX table -> {TEX_OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
