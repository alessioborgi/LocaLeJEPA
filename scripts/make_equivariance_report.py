"""Aggregate the ImageNet-1K geometric-backbone Yoda-probe results into
``report_equivariance.md``.

Reads each eval's ``results_multiseed.json`` (written by
``eval_angle_probe_multiseed.py``) and emits a Markdown table of R2 / MAE
(mean +/- std over 10 splits) per figurine. Backbones whose eval has not
finished yet are listed as *pending*, so the report is safe to run at any time
(e.g. as an ``afterany`` Slurm step after the eval jobs).

Usage:
    python scripts/make_equivariance_report.py            # -> report_equivariance.md
    python scripts/make_equivariance_report.py --out X.md
"""

import argparse
import json
from pathlib import Path

# (display name, regularizer label, eval output_folder) in report order.
BACKBONES = [
    ("d4rn50_sigreg_in1k", "D4-ResNet-50 (equivariant) + LeJEPA/SIGReg",
     "logs/eval_angle_probe_yoda_d4rn50_sigreg_in1k"),
    ("d4rn50_rdmreg_in1k", "D4-ResNet-50 (equivariant) + RectifiedLpJEPA/RDMReg",
     "logs/eval_angle_probe_yoda_d4rn50_rdmreg_in1k"),
    ("hvit_sigreg_in1k", "Hyperbolic ViT-S/8 + LeJEPA/SIGReg",
     "logs/eval_angle_probe_yoda_hvit_sigreg_in1k"),
    ("hvit_rdmreg_in1k", "Hyperbolic ViT-S/8 + RectifiedLpJEPA/RDMReg",
     "logs/eval_angle_probe_yoda_hvit_rdmreg_in1k"),
    ("d4rn50_localballreg_l01_k2_in1k", "D4-ResNet-50 (equivariant) + local BallReg (λ0.1, k2)",
     "logs/eval_angle_probe_yoda_d4rn50_localballreg_l01_k2_in1k"),
    ("d4rn50_localballreg_l01_k4_in1k", "D4-ResNet-50 (equivariant) + local BallReg (λ0.1, k4)",
     "logs/eval_angle_probe_yoda_d4rn50_localballreg_l01_k4_in1k"),
    ("d4rn50_localballreg_l03_k2_in1k", "D4-ResNet-50 (equivariant) + local BallReg (λ0.3, k2)",
     "logs/eval_angle_probe_yoda_d4rn50_localballreg_l03_k2_in1k"),
    ("d4rn50_localsigreg_l01_k4_in1k", "D4-ResNet-50 (equivariant) + local SIGReg (λ0.1, k4)",
     "logs/eval_angle_probe_yoda_d4rn50_localsigreg_l01_k4_in1k"),
    ("d4rn50_localballreg_l01_dynk_in1k", "D4-ResNet-50 (equivariant) + local BallReg (λ0.1, k1→10 dyn)",
     "logs/eval_angle_probe_yoda_d4rn50_localballreg_l01_dynk_in1k"),
    ("hvit_localballreg_l01_k2_in1k", "Hyperbolic ViT-S/8 + local BallReg (λ0.1, k2)",
     "logs/eval_angle_probe_yoda_hvit_localballreg_l01_k2_in1k"),
    ("hvit_localballreg_l01_k4_in1k", "Hyperbolic ViT-S/8 + local BallReg (λ0.1, k4)",
     "logs/eval_angle_probe_yoda_hvit_localballreg_l01_k4_in1k"),
    ("hvit_localballreg_l03_k2_in1k", "Hyperbolic ViT-S/8 + local BallReg (λ0.3, k2)",
     "logs/eval_angle_probe_yoda_hvit_localballreg_l03_k2_in1k"),
    ("hvit_localsigreg_l01_k4_in1k", "Hyperbolic ViT-S/8 + local SIGReg (λ0.1, k4)",
     "logs/eval_angle_probe_yoda_hvit_localsigreg_l01_k4_in1k"),
    ("hvit_localballreg_l01_dynk_in1k", "Hyperbolic ViT-S/8 + local BallReg (λ0.1, k1→10 dyn)",
     "logs/eval_angle_probe_yoda_hvit_localballreg_l01_dynk_in1k"),
]


def _load(folder: str):
    p = Path(folder) / "results_multiseed.json"
    if not p.exists():
        return None
    with p.open(encoding="utf-8") as f:
        summary = json.load(f)
    return next(iter(summary.values())) if summary else None


def _cell(angle):
    if angle is None:
        return "—"
    return (f'{angle["r2_mean"]:.4f}±{angle["r2_std"]:.4f} / '
            f'{angle["mae_mean"]:.2f}±{angle["mae_std"]:.2f}°')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="report_equivariance.md")
    args = ap.parse_args()

    rows, n_done = [], 0
    for name, label, folder in BACKBONES:
        b = _load(folder)
        if b is None:
            rows.append(f"| `{name}` | {label} | *pending* | *pending* |")
            continue
        n_done += 1
        angles = b.get("angles", {})
        a0, a1 = angles.get("angle0"), angles.get("angle1")
        rows.append(f"| `{name}` | {label} | {_cell(a0)} | {_cell(a1)} |")

    lines = [
        "# Equivariant / Hyperbolic Backbones on ImageNet-1K — Yoda Probe Results",
        "",
        f"Auto-generated by `scripts/make_equivariance_report.py`. "
        f"{n_done}/{len(BACKBONES)} evals complete.",
        "",
        "Frozen backbone (LeJEPA / RectifiedLpJEPA pretrained on ImageNet-1K, "
        "`trainer.max_epochs=100`), Yoda rotation-angle linear probe, "
        "mean ± std over 10 random 60/20/20 splits. Each cell is R² / MAE (degrees).",
        "",
        "| Backbone | Pretraining | figurine 0 (R² / MAE) | figurine 1 (R² / MAE) |",
        "|---|---|---|---|",
        *rows,
        "",
        "**D4-ResNet-50** uses the equivision escnn backbone with an *equivariant* "
        "output head (`pool=equivariant`): the embedding transforms under D4 by the "
        "regular representation rather than being pooled to an invariant vector. "
        "**Hyperbolic ViT-S/8** embeds on the Poincaré ball (hyp_c=0.1, clip_r=2.3).",
        "",
        "Imagenette-pretrained baselines and the full learning-curve / hyperparameter "
        "tables are in `reports/equivariance_report.md`.",
        "",
    ]
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {args.out} ({n_done}/{len(BACKBONES)} backbones populated)")


if __name__ == "__main__":
    main()
